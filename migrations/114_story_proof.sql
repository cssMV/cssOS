-- CSSOS_WAVE_1822 — 故事页「先给证据, 再要行动」(Jing)
--
-- 病因(埋点+分页漏斗共同定位): 2,250 人停留 15 秒以上、511 人滑动过、39 人读完四分之三,
--   而提问只有 5 次(其中 1 次还是自测)。提问框在【首屏就看得见】, 所以不是"看不见",
--   是"不想问"。缺的不是兴趣, 是一个开口的理由 —— 现在框里只有一句承诺
--   「她会亲口回答」, 读者无法判断问了会怎样、值不值得。
--
-- 修法: 在输入框上方直接放【她真实说过的一段话】。承诺要人相信, 证据让人验证,
--   后者便宜得多。
--
-- 为什么存库而不是每次现生成: 落地页每天 5,000 次浏览, 每次调一次 LLM 既贵又慢
--   (KIE 抖动时要 15-30 秒), 而这段话对同一章的所有读者是一样的。预生成一次即可。
--   将来想换问题, 重跑填充脚本就行。
--
-- 刻意【截断】而不是存全文: 证据的作用是证明"它是活的", 不是替读者把问题问完。
--   留半句, 才有人想接着问。

ALTER TABLE story_chapters ADD COLUMN IF NOT EXISTS proof_q TEXT;
ALTER TABLE story_chapters ADD COLUMN IF NOT EXISTS proof_a TEXT;
