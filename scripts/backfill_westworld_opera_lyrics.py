def scene_rows():
    query = (
        "select title, id, coalesce(source_run_id,'') "
        "from user_works "
        f"where root_work_id = '{ROOT_WORK_ID}' and structure_role = 'scene' "
        "order by created_at;"
    )
    output = subprocess.check_output(
        ["psql", DB_URL, "-At", "-F", "\t", "-c", query],
        text=True,
    )
    rows = []
    for raw in output.splitlines():
        title, work_id, run_id = raw.split("\t")
        rows.append({"title": title, "work_id": work_id, "run_id": run_id})
    return rows


def lyric_payload(title: str, lyric_text: str):
    lines = []
    cursor = 0.0
    for raw in lyric_text.splitlines():
        text = raw.rstrip()
        if not text:
            cursor += 0.45
            continue
        lines.append({"t": round(cursor, 2), "text": text})
        cursor += 1.55 if text.startswith("[") else 2.25
    return {
        "lang": "zh",
        "lines": lines,
        "schema": "css.lyrics.v1",
        "title": title,
    }


def write_run_lyrics(run_id: str, title: str, lyric_text: str):
    if not run_id:
        return
    base = RUNS_DIR / run_id / "build"
    if not base.exists():
        return
    payload = lyric_payload(title, lyric_text)
    primary = base / "lyrics.json"
    primary.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    nested_dir = base / "lyrics"
    nested_dir.mkdir(parents=True, exist_ok=True)
    (nested_dir / "lyrics.primary.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (nested_dir / "lyrics.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (base / "lyrics.txt").write_text(lyric_text.strip() + "\n", encoding="utf-8")


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def update_work_preview(work_id: str, lyric_text: str):
    sql = (
        "update user_works "
        f"set lyrics_preview = {sql_literal(lyric_text.strip())}, updated_at = now() "
        f"where id = {sql_literal(work_id)};"
    )
    subprocess.check_call(["psql", DB_URL, "-q", "-c", sql])


def main():
    if not DB_URL:
        raise SystemExit("DATABASE_URL is required")
    rows = scene_rows()
    missing = [row["title"] for row in rows if row["title"] not in LYRICS_BY_TITLE]
    if missing:
        raise SystemExit(f"missing lyrics for titles: {missing}")
    for row in rows:
        lyric_text = LYRICS_BY_TITLE[row["title"]].strip()
        write_run_lyrics(row["run_id"], row["title"], lyric_text)
        update_work_preview(row["work_id"], lyric_text)
        print(f"updated {row['title']}")


if __name__ == "__main__":
    main()
