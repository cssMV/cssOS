def main():
    old = json.load(open("/tmp/rumi-shotlist.json")) if os.path.exists("/tmp/rumi-shotlist.json") \
          else json.load(open(f"{ROOT}/docs/mv/rumi-shotlist.json"))
    new, md = {}, []
    for key, rows in (("p1", P1), ("p2", P2), ("p3", P3)):
        odur = {r[1]: r[4] for r in old[key]}
        assert len(rows) == len(old[key]), f"{key}: 新 {len(rows)} 镜 vs 原 {len(old[key])} 镜"
        out, t = [], 0.0
        for num, desc, who in rows:
            d = odur[num]
            out.append([key, num, round(t,2), round(t+d,2), d, desc, who])
            t += d
        new[key] = out
        cnt = {}
        for r in out: cnt[r[6]] = cnt.get(r[6],0)+1
        print(f"{key}: {len(out)} 镜 -> {t:.1f}s (沿用原轴)  {cnt}")
    json.dump(new, open(f"{ROOT}/docs/mv/rumi-shotlist-v2.json","w"), ensure_ascii=False, indent=1)
    tot = sum(len(v) for v in new.values())
    print(f"--- 清单 163 镜, 实际写出 {tot} 镜 " + ("✅ 无遗漏" if tot==163 else "⚠️ 有漏!"))

main()
